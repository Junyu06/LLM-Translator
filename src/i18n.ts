export type StringKey = keyof typeof STRINGS.en;

export function translator(lang: UiLang) {
  const table = STRINGS[lang] ?? STRINGS.en;
  return (key: StringKey, values?: Record<string, string | number>) => {
    let text: string = table[key];
    for (const [name, value] of Object.entries(values ?? {})) {
      text = text.replace(`{${name}}`, String(value));
    }
    return text;
  };
}

export function languageName(uiLang: UiLang, code: string) {
  return LANG_NAMES[uiLang]?.[code] ?? code.toUpperCase();
}
